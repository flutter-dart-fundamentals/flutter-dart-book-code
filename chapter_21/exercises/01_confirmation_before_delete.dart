// Exercise 01 - Confirmation Before Delete

/*  */


Modify the app so that tapping the trash icon shows an AlertDialog asking "Are you sure you want to delete this task?" with "Yes" and "No" buttons. Only delete the task if the user confirms by pressing Yes. This exercise practices nesting dialogs inside tap handlers and managing the flow of user decisions. Notice that this exercise builds two layers of safety on top of the destructive action: first, a precise icon target (already in the chapter); second, an explicit confirmation step. Mature apps use both.
