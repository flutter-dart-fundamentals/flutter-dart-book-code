Add backgroundColor: Colors.lightBlue to the Scaffold to change the body's background color. Notice how the body color changes while the AppBar color stays the same, because AppBar has its own backgroundColor parameter that is separate from Scaffold's. Try a few different colors from the Colors class such as Colors.amber, Colors.teal, and Colors.grey to see how each one affects the overall feel of the screen.
