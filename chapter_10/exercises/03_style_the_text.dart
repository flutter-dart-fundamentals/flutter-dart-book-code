Experiment with the TextStyle class on the body Text widget. Start by changing fontSize to different values such as 16, 32, and 48 to see how it affects the text size. Then set fontWeight to FontWeight.w300 for a thin appearance and compare it to FontWeight.w900 for the heaviest weight. Finally add a color property using any color from the Colors class. Remember that TextStyle is just a Dart class with named parameters, the same pattern you have been using throughout this chapter.
